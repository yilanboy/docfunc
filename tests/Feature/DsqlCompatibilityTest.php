<?php

use App\Listeners\DisconnectExpiredDsqlConnection;
use Bref\LaravelDsql\DsqlConnection;
use Illuminate\Database\Events\ConnectionEstablished;
use Illuminate\Http\Request;
use Illuminate\Http\Response;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Event;
use Laravel\Octane\Events\RequestTerminated;

test('all migrations compile cleanly through DsqlSchemaGrammar without unsupported DDL', function () {
    $dsqlConnection = new DsqlConnection(
        new PDO('sqlite::memory:'),
        'postgres',
        '',
        [
            'driver'         => 'dsql',
            'name'           => 'dsql_pretend',
            'database'       => 'postgres',
            'prefix'         => '',
            'prefix_indexes' => true,
            'search_path'    => 'public',
        ],
    );

    config(['database.connections.dsql_pretend' => ['driver' => 'dsql_pretend']]);
    DB::extend('dsql_pretend', fn () => $dsqlConnection);

    $originalDefault = DB::getDefaultConnection();
    $migrationFiles = glob(database_path('migrations/*.php'));
    sort($migrationFiles);

    expect($migrationFiles)->not->toBeEmpty();

    try {
        DB::setDefaultConnection('dsql_pretend');

        $queries = $dsqlConnection->pretend(function () use ($migrationFiles): void {
            foreach ($migrationFiles as $file) {
                $migration = require $file;
                $migration->up();
                $migration->down();
            }
        });
    } finally {
        DB::setDefaultConnection($originalDefault);
        DB::purge('dsql_pretend');
    }

    $sqlStatements = array_column($queries, 'query');
    $combinedSql = strtolower(implode("\n", $sqlStatements));
    $ddlSql = strtolower(implode("\n", array_filter(
        $sqlStatements,
        fn (string $sql): bool => str_starts_with(strtolower($sql), 'create ')
            || str_starts_with(strtolower($sql), 'alter ')
            || str_starts_with(strtolower($sql), 'drop '),
    )));

    expect($sqlStatements)->not->toBeEmpty();
    expect($combinedSql)->not->toContain('truncate ');
    expect($ddlSql)->not->toMatch('/\bjsonb?\b/');
    expect($ddlSql)->not->toContain('alter index ');
    expect($ddlSql)->toContain('generated by default as identity (cache 1)');
    expect($ddlSql)->toContain('create index async ');
});

test('whereLike compiles to case-insensitive ilike on DsqlQueryGrammar', function () {
    $dsqlConnection = new DsqlConnection(
        new PDO('sqlite::memory:'),
        'postgres',
        '',
        ['driver' => 'dsql', 'database' => 'postgres', 'prefix' => ''],
    );

    $sql = $dsqlConnection->table('tags')
        ->whereLike('name', '%laravel%')
        ->toSql();

    expect(strtolower($sql))->toContain('ilike');
});

test('DisconnectExpiredDsqlConnection only disconnects DSQL connections after max age', function () {
    DisconnectExpiredDsqlConnection::reset();

    $dsqlConnection = new DsqlConnection(
        new PDO('sqlite::memory:'),
        'postgres',
        '',
        ['driver' => 'dsql', 'name' => 'dsql_octane_test', 'database' => 'postgres', 'prefix' => ''],
    );

    config(['database.connections.dsql_octane_test' => ['driver' => 'dsql_octane_test']]);
    DB::extend('dsql_octane_test', fn () => $dsqlConnection);
    DB::connection('dsql_octane_test');

    $listener = new DisconnectExpiredDsqlConnection;
    $event = new RequestTerminated(app(), app(), Request::create('/'), new Response);

    try {
        Event::dispatch(new ConnectionEstablished($dsqlConnection));

        $this->travel(49)->minutes();
        $listener->handle($event);
        expect($dsqlConnection->getRawPdo())->toBeInstanceOf(PDO::class);

        $this->travel(1)->minutes();
        $listener->handle($event);
        expect($dsqlConnection->getRawPdo())->toBeNull();
    } finally {
        DisconnectExpiredDsqlConnection::reset();
        DB::purge('dsql_octane_test');
    }
});
